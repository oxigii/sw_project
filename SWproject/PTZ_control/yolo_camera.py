import os
from pathlib import Path
import time

import cv2
from dotenv import load_dotenv
from ultralytics import YOLO


# ============================================================
# 설정
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[1]
load_dotenv(PROJECT_ROOT / ".env")
RTSP_URL = os.getenv("PTZ_RTSP_URL", "")

# YOLO 모델
# 처음 실행하면 자동으로 다운로드됨
MODEL_PATH = "yolo11n.pt"

# 신뢰도 기준
CONFIDENCE = 0.4


# ============================================================
# YOLO 모델 로드
# ============================================================

print("YOLO 모델 로딩 중...")

model = YOLO(MODEL_PATH)

print("✅ YOLO 모델 로딩 완료")


# ============================================================
# 카메라 연결
# ============================================================

print("카메라 연결 중...")

cap = cv2.VideoCapture(RTSP_URL, cv2.CAP_FFMPEG)

# 버퍼를 최대한 작게
cap.set(cv2.CAP_PROP_BUFFERSIZE, 1)

if not cap.isOpened():
    print("❌ 카메라 연결 실패")
    print("RTSP 주소를 확인하세요.")
    exit()

print("✅ 카메라 연결 성공")
print("ESC 또는 Q를 누르면 종료합니다.")


# ============================================================
# FPS 계산
# ============================================================

prev_time = time.time()
frame_count = 0
fps = 0


# ============================================================
# 영상 + YOLO
# ============================================================

while True:

    # --------------------------------------------------------
    # 카메라 프레임 읽기
    # --------------------------------------------------------

    ret, frame = cap.read()

    if not ret:
        print("⚠️ 영상 수신 실패")
        time.sleep(0.1)
        continue


    # --------------------------------------------------------
    # YOLO 객체 탐지
    # --------------------------------------------------------

    results = model(
        frame,
        conf=CONFIDENCE,
        verbose=False
    )


    # --------------------------------------------------------
    # YOLO 결과를 영상에 그리기
    # --------------------------------------------------------

    annotated_frame = results[0].plot()


    # --------------------------------------------------------
    # FPS 계산
    # --------------------------------------------------------

    frame_count += 1

    current_time = time.time()

    if current_time - prev_time >= 1.0:

        fps = frame_count / (current_time - prev_time)

        frame_count = 0
        prev_time = current_time


    # --------------------------------------------------------
    # FPS 표시
    # --------------------------------------------------------

    cv2.putText(
        annotated_frame,
        f"FPS: {fps:.1f}",
        (20, 40),
        cv2.FONT_HERSHEY_SIMPLEX,
        1,
        (0, 255, 0),
        2
    )


    # --------------------------------------------------------
    # 영상 표시
    # --------------------------------------------------------

    cv2.imshow("YOLO Camera", annotated_frame)


    # --------------------------------------------------------
    # 종료
    # --------------------------------------------------------

    key = cv2.waitKey(1) & 0xFF

    if key == 27 or key == ord("q"):
        break


# ============================================================
# 종료
# ============================================================

cap.release()
cv2.destroyAllWindows()

print("카메라 + YOLO 종료")

